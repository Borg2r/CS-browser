fn tile_style(ch: u8) -> Option<(f32, u8)> {
    match ch {
        b'#' => Some((4.2, 1)),
        b'H' => Some((6.2, 1)),
        b'c' => Some((0.85, 3)),
        b'k' => Some((1.65, 3)),
        b'D' => Some((2.8, 2)),
        b'=' => Some((0.9, 4)),
        _ => standard_tile(ch),
    }
}

// Solid ceilings share server and client collision. The atrium is taller,
// while all undersides leave enough clearance for a standing player's jump.
const EXTRAS: &[Aabb] = &[
    Aabb { min: [-48.0, 4.4, -50.0], max: [8.0, 4.7, -32.0], mat: 1, var: 0 },
    Aabb { min: [-48.0, 4.4, -32.0], max: [-20.0, 4.7, -2.0], mat: 1, var: 1 },
    Aabb { min: [-20.0, 9.0, -32.0], max: [10.0, 9.3, -2.0], mat: 1, var: 2 },
    Aabb { min: [10.0, 4.4, -28.0], max: [48.0, 4.7, -2.0], mat: 1, var: 3 },
    Aabb { min: [2.0, 6.6, 0.0], max: [48.0, 7.0, 50.0], mat: 1, var: 4 },
];

pub fn build() -> Map {
    Map::from_rows(
        MapId::Norheim,
        ROWS,
        tile_style,
        EXTRAS,
        [[[-25.0, 18.0], [-25.0, 18.0]], [[8.0, -44.0], [8.0, -44.0]]],
    )
}
