fn tile_style(ch: u8) -> Option<(f32, u8)> {
    match ch {
        b'C' => Some((2.6, 2)),
        b'D' => Some((5.2, 2)),
        _ => standard_tile(ch),
    }
}

const EXTRAS: &[Aabb] = &[];

pub fn build() -> Map {
    Map::from_rows(
        MapId::Dockyard,
        ROWS,
        tile_style,
        EXTRAS,
        [
            [[-23.0, 45.0], [23.0, 45.0]],
            [[-23.0, -45.0], [23.0, -45.0]],
        ],
    )
}
