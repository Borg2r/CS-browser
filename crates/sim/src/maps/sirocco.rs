pub fn build() -> Map {
    // Raised roofs shelter the west tunnel and both gateways without blocking
    // standing players or the common ground-level navigation mesh.
    const EXTRAS: [Aabb; 3] = [
        Aabb { min: [-40.0, 3.6, -18.0], max: [-28.0, 4.3, 12.0], mat: 1, var: 1 },
        Aabb { min: [-4.0, 4.2, -6.0], max: [2.0, 7.0, -2.0], mat: 1, var: 2 },
        Aabb { min: [32.0, 4.2, 10.0], max: [38.0, 7.0, 14.0], mat: 1, var: 3 },
    ];
    Map::from_rows(MapId::Sirocco, &ROWS, standard_tile, &EXTRAS,
                   [[[-23.0, 40.0], [23.0, 40.0]], [[-20.0, -42.0], [20.0, -42.0]]])
}
